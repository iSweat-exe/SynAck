// Random banner for a card, generated by the DiceBear API from a seed (stable for a given seed), in the
// palette of the site. Temporary: banners will come from the CMS.
export function bannerUrl(seed: string) {
  const params = new URLSearchParams({
    seed,
    backgroundColor: "fff0f8,ffe0f0,fec2e1",
    shape1Color: "fb84c3,f656ab,fda3d2",
    shape2Color: "a9a0a5,d1cace,e6e1e4",
    shape3Color: "2e292c,453e42,121011",
  });
  return `https://api.dicebear.com/9.x/shapes/svg?${params.toString()}`;
}
